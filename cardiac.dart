                                Code STEMI Direct to Cath Lab

PURPOSE:
Early identification and delivery of select STEMI patients (directly from the field to the catheterization
lab) to provide the highest level of care and expedite PCI treatment.

Inclusion Criteria:
     Chest pain (or symptoms felt to be ischemic in origin).
     High quality EKG, with ST elevation of > 2 mm in 2 contiguous leads.
     Absence of exclusion criteria.
Exclusion Criteria
     Wide QRS complex (>0.1 sec).
     Intubated.
     Severe respiratory distress.
     Cardiac arrest.
     DNR or on-going Hospice care.
     Severe, active bleeding.
     Head or another serious trauma.

