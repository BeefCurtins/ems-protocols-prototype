                                Hypothermia/Frostbite

Guidelines of Care:
   1. General Supportive Care
   2. Oxygen via NC as tolerated, pulse oximeter.
   3. Cardiac Monitor/12 Lead ECG.
   4. Check core temp < 35c (95 Fahrenheit) go to Hypothermia Guidelines.
   5. Establish IV of NS with warm fluids if possible.
   6. Attend to injury sites:
           Protect injured areas from pressure, trauma, and friction.
           Do not rub or break blisters.
           Do not permit limb to thaw, if risk to refreeze is present.
           Do not permit patient to ambulate once limb has started to thaw.
           Keep patient warm with blankets.
           Give warm fluids by mouth if patient is awake and alert.
           Do not withhold any treatment for fear of agitating patient.
   7. Transport

Medical Control:
  1. Consider Morphine 0.1 mg/kg slow IVP max 10mg, or Fentanyl 50mcg IV/IO/IM/IN for
  pain.

Hypothermia
  1. Actions for all patients.
           Remove wet clothing.
           Protect against heat loss and wind chill.
           Avoid rough movement and excessive activity.
           Monitor core temp and cardiac rhythm.
           Treat major trauma as priority and hypothermia as second.
  2. Assess responsiveness, breathing, and pulse.
           If pulse / breathing absent initiate CPR, including ACLS procedures as necessary
              (defibrillation, intubation) if possible ventilate with warm humid oxygen.
           If patient core temp <30c (86 Fahrenheit), continue CPR, withhold IV meds,
              transport.
           If core temp >30c (86 Fahrenheit), continue CPR, give IV medications
              as appropriate for dysrhythmia, transport.
  3. If patient has pulse/breathing, administer warm, humidified oxygen if possible, initiate IV
      fluids (warm) of 100-150 ml/hr.
  4. Determine glucose (venous) level. If glucose <60 administer 100cc of a D10 solution
      (25g/250cc bag) over 10 minutes. A blood glucose reading should be assessed after 10
      minutes. If after the 10 minute drip the reading is <60 or if the pt. has not regained
      consciousness, continue dosing @ above referenced rate.

   5. Continue external warming carefully with warm packs to armpits, neck, groin as
      appropriate.
   6. Monitor patient's condition carefully.
   7. Gentle/careful transport.
   8. Contact Medical Control if necessary for further orders.

Consideration:
          When the body's core temp decreases, the body will first respond by shivering. This is an
attempt by the body to generate heat from muscle activity. Vasoconstriction will shunt blood
from the skin and an increase in the patient's metabolic rate will increase heat.
          If this mechanism cannot compensate for severe temp drops and the body's systems begin
to fail, i.e. respiratory function will deteriorate and lead to hypoxemia. The patient may also
develop dysrhythmias and cardiopulmonary arrest may occur. Patients are particularly at risk for
dysrhythmias during the warming phase of treatment. HANDLE THESE PATIENTS
GENTLY.

Clinical Presentation for moderate hypothermia may include:
     Conscious but often lethargic condition, shivering, skin pale and cold
Clinical Presentation for severe hypothermia may include:
     Unconsciousness or decrease LOC, ice cold skin, inaudible heart sounds, unobtainable
        BP or severe hypotension, un-reactive pupils, slow or absent respirations.

Avoid:
    Hyperventilating patient; drop in CO2 may cause VF!
    Rubbing skin.
    Re-warming extremities first, re-warm core body temp if possible to prevent
       complications to limbs.
    All unnecessary rough movements.
    With the hypothermic patient:
             Once CPR is started -DO NOT GIVE UP!!!
             Patients who are severely hypothermic are generally not given medications
                 until they are warmed to 86F or 30C.
             Those that are moderately hypothermic are given medications but at increased
                 intervals between doses.

