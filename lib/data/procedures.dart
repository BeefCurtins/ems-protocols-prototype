    category: 'Procedures',    content: r'''Tourniquet Use
Indications:
       Tourniquet should be used to control hemorrhagic wounds that have not responded
       adequately to direct pressure or in situations extremity bleeding with need for
       additional interventions (example; significant extremity bleeding with airway
       compromise). A tourniquet should be used to quickly control bleeding, freeing up
       personnel to concentrate on airway issues.

Precautions:
   1. BSI.
   2. Tourniquet applied incorrectly can increase blood loss and lead to death.
   3. Applying can cause nerve and tissue damage whether applied correctly or not. Proper
      patient selection is of utmost importance.
   4. Damage is unlikely if the tourniquet is removed within 2 hours.
   5. Never cover tourniquet with clothing, bandages or packaging.

Technique:
   1. Attempt to control hemorrhage with direct pressure or pressure dressing.
   2. If unable to control hemorrhage, apply tourniquet using the procedure below and
      following above considerations.
           Select commercially manufactured tourniquet, cravat or BP cuff and apply to the
              extremity proximal to the wound. (Preferably on a single-bone structure above the
              wound about 2 in.) Do not place over joint.
           Tighten until bleeding is controlled. (Consider 2cd tourniquet 2” above first if first
              does not adequately control the bleed.)
           Record time, date, and initials of person who applied tourniquet. (Example,
              08/12/16 19:30 GC, indicated that tourniquet was applied on 6/16/14 at 7:30 pm
              by medic GC) Should be written on a piece of tape and secured on the tourniquet,
              on the designated place on the tourniquet, or on the patient skin above the
              tourniquet with a permanent marker.
           Must be left uncovered so the site can be monitored for recurrent hemorrhage.
           Keep tourniquet on throughout transport, and assure a report is provided while
              in transit and on arrival at the hospital (a correctly applied tourniquet should be
              removed by the receiving facility.)
           Continue to monitor patient vitals, and observe the wound site often during
              transport.
           Ensure receiving facility staff members are clearly informed that a tourniquet has
              been applied on the patient prior to leaving the emergency room.
