Normal Mental Capacity:
An individual who is alert, oriented, and has the capacity to understand the circumstances
surrounding their illness or impairment, as well as the possible risks associated with refusing
treatment and/or transport typically is considered to have normal mental capacity. The
individual’s judgment must also not be significantly impaired by illness, injury or drugs/alcohol
intoxication. Individuals who have attempted suicide, verbalized suicidal intent, or have other
factors that lead EMS providers to suspect suicidal intent, should not be regarded as having
normal mental capacity and may not decline transport to a medical facility.

Patient Care Guideline:
   1. Obtain a complete set of vital signs and complete an initial assessment with
       particular attention to the individual’s neurologic and mental status.
   2. Determine the individual’s capacity to make a valid judgment concerning the
       extent of the individual’s illness or injury. If the EMS provider has doubts about
       whether the individual has the mental capacity to refuse or if the patient lacks
       capacity, the EMS provider should contact on-line medical control.
   3. If patient has capacity, clearly explain to the individual and all responsible parties
       the possible risks and overall concerns with regards to refusing care.
   4. Perform appropriate medical care with the consent of the individual.
   5. Complete the patient care report clearly documenting the initial assessment
       findings and the discussions with all involved individuals regarding the possible
       consequences of refusing additional pre-hospital care and/or transportation.

Key Notes:
 1. An adult or emancipated minor, who has demonstrated possessing sufficient mental
     capacity for making decisions, has the right to determine the course of their medical
     care, including the refusal of care. These individuals must be advised of the risks and
     consequences resulting from refusal of medical care.
 2. An individual determined to lack mental capacity by EMS providers or on-line medical
     direction should not be allowed to refuse care against medical advice or to be released
     at the scene. Mental illness, drugs, alcohol intoxication, or physical/mental impairment
     may significantly impair an individual’s mental capacity. Individuals who have
     attempted suicide, verbalized suicidal intent, or have other factors that lead EMS
     providers to suspect suicidal intent, should not be regarded as having demonstrated
     sufficient or normal mental capacity.
 3. EMS providers should not put themselves in danger by attempting to treat and/or
     transport an individual who refuses care.
 4. Always act in the best interest of the patient. EMS providers, with the support of
     medical direction, must strike a balance between abandoning the patient and forcing
     care.
 5. The legal definition of a minor is determined by each state. Therefore, one should
